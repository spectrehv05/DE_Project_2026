
-- WhatsApp Messaging Database
-- CP1: Schema Creation

CREATE TABLE users (
    user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone_e164 VARCHAR(20) NOT NULL UNIQUE,
    display_name VARCHAR(100) NOT NULL,
    about TEXT,
    is_business BOOLEAN NOT NULL DEFAULT FALSE,
    joined_on DATE NOT NULL,
    last_seen_at TIMESTAMPTZ,
    status VARCHAR(20) NOT NULL
);

CREATE TABLE chats (
    chat_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_type VARCHAR(20) NOT NULL,
    group_name VARCHAR(100),
    created_by INTEGER NOT NULL REFERENCES users(user_id),
    created_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE media (
    media_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uploader_id INTEGER NOT NULL REFERENCES users(user_id),
    media_type VARCHAR(30) NOT NULL,
    mime_type VARCHAR(100),
    size_bytes BIGINT NOT NULL CHECK (size_bytes >= 0),
    sha256 CHAR(64),
    uploaded_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE chat_members (
    chat_id INTEGER NOT NULL REFERENCES chats(chat_id),
    user_id INTEGER NOT NULL REFERENCES users(user_id),
    role VARCHAR(20) NOT NULL,
    joined_at TIMESTAMPTZ NOT NULL,
    left_at TIMESTAMPTZ,
    is_muted BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (chat_id, user_id)
);

CREATE TABLE messages (
    message_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_id INTEGER NOT NULL REFERENCES chats(chat_id),
    sender_id INTEGER NOT NULL REFERENCES users(user_id),
    sent_at TIMESTAMPTZ NOT NULL,
    message_type VARCHAR(20) NOT NULL,
    body TEXT,
    media_id INTEGER REFERENCES media(media_id),
    reply_to_message_id INTEGER REFERENCES messages(message_id),
    is_forwarded BOOLEAN NOT NULL DEFAULT FALSE,
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    edited_at TIMESTAMPTZ
);

CREATE TABLE message_receipts (
    message_id INTEGER NOT NULL REFERENCES messages(message_id),
    user_id INTEGER NOT NULL REFERENCES users(user_id),
    delivered_at TIMESTAMPTZ,
    read_at TIMESTAMPTZ,
    PRIMARY KEY (message_id, user_id)
);

CREATE TABLE calls (
    call_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_id INTEGER NOT NULL REFERENCES chats(chat_id),
    caller_id INTEGER NOT NULL REFERENCES users(user_id),
    call_type VARCHAR(20) NOT NULL,
    started_at TIMESTAMPTZ NOT NULL,
    answered_at TIMESTAMPTZ,
    ended_at TIMESTAMPTZ,
    status VARCHAR(20) NOT NULL
);

CREATE TABLE devices (
    device_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(user_id),
    device_type VARCHAR(20) NOT NULL,
    app_version VARCHAR(30),
    registered_at TIMESTAMPTZ NOT NULL,
    last_active_at TIMESTAMPTZ
);

CREATE TABLE blocked_users (
    blocker_id INTEGER NOT NULL REFERENCES users(user_id),
    blocked_id INTEGER NOT NULL REFERENCES users(user_id),
    blocked_at TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (blocker_id, blocked_id),
    CHECK (blocker_id <> blocked_id)
);

-- Useful indexes for common relationships and queries
CREATE INDEX idx_messages_chat_sent
    ON messages(chat_id, sent_at);

CREATE INDEX idx_messages_sender
    ON messages(sender_id);

CREATE INDEX idx_receipts_user
    ON message_receipts(user_id);

CREATE INDEX idx_devices_user
    ON devices(user_id);

CREATE INDEX idx_calls_chat
    ON calls(chat_id);
