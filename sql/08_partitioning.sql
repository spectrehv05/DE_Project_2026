-- =====================================================================
-- WhatsApp DBMS Project: CP4 / Phase 5, partitioning design for `messages`
--
-- Goal: keep the table fast and maintainable at 100x the seed volume
-- (about 12 million messages) by splitting it into one partition per month.
--
-- Run after 01_schema.sql, 02_load_data.sql and 05_indexes.sql:
--   psql -d whatsapp_db -f sql/08_partitioning.sql
--
-- The script builds a SEPARATE table, messages_partitioned, and copies the rows
-- of `messages` into it. The original table and the benchmark results already
-- committed for CP2 / CP3 are not touched, so everything stays reproducible.
-- Safe to re-run (it drops and rebuilds messages_partitioned).
--
-- DESIGN DECISIONS (full reasoning in docs/05_scalability_report.md, section 5)
--   * Method: RANGE on sent_at, one partition per calendar month (IST).
--     - Most heavy queries (R08, R10, R14, R17, R19, R20) filter on a time range,
--       so the planner can skip months it does not need (partition pruning).
--     - Old months can be archived with DETACH PARTITION, which is instant,
--       instead of a huge DELETE followed by VACUUM.
--     - New writes (W01) always land in the newest partition, so only a small,
--       hot set of index pages is touched.
--   * Bounds carry an explicit +05:30 offset, so the partition boundaries do not
--     depend on the TimeZone setting of whoever runs this script.
--   * A DEFAULT partition catches any row outside the created months, so an
--     INSERT never fails because a month partition is missing.
--
-- THE PRIMARY KEY RULE
--   On a partitioned table every PRIMARY KEY / UNIQUE constraint must include the
--   partition key. messages(message_id) therefore becomes PRIMARY KEY
--   (message_id, sent_at). Because message_id alone is no longer unique as far as
--   PostgreSQL is concerned, two things change:
--     1. message_receipts.message_id and messages.reply_to_message_id can no
--        longer be FOREIGN KEYs to messages. They are left unenforced here; the
--        app (or a trigger) must keep them valid. This is the price of partitioning.
--     2. message_id uniqueness is guaranteed only because it comes from one
--        identity sequence, not by the database.
--   Lookups by message_id alone (R16, R25, W03) still use the primary-key index
--   (message_id is its leading column), but they probe every partition.
-- =====================================================================

SET search_path TO public;

DROP TABLE IF EXISTS messages_partitioned CASCADE;

-- ---------------------------------------------------------------------
-- 1. Parent table: same columns and CHECK constraints as `messages`
-- ---------------------------------------------------------------------
CREATE TABLE messages_partitioned (
    message_id          INTEGER GENERATED BY DEFAULT AS IDENTITY,
    chat_id             INTEGER NOT NULL REFERENCES chats(chat_id),
    sender_id           INTEGER NOT NULL REFERENCES users(user_id),
    sent_at             TIMESTAMPTZ NOT NULL,
    message_type        VARCHAR(20) NOT NULL,
    body                TEXT,
    media_id            INTEGER REFERENCES media(media_id),
    reply_to_message_id INTEGER,            -- FK to messages not possible, see PRIMARY KEY RULE
    is_forwarded        BOOLEAN NOT NULL DEFAULT FALSE,
    is_deleted          BOOLEAN NOT NULL DEFAULT FALSE,
    edited_at           TIMESTAMPTZ,
    PRIMARY KEY (message_id, sent_at),      -- must contain the partition key
    CONSTRAINT ck_msgp_type    CHECK (message_type IN ('TEXT','IMAGE','VIDEO','AUDIO','DOCUMENT','LOCATION')),
    CONSTRAINT ck_msgp_media   CHECK (message_type NOT IN ('TEXT','LOCATION') OR media_id IS NULL),
    CONSTRAINT ck_msgp_edit    CHECK (edited_at IS NULL OR edited_at >= sent_at),
    CONSTRAINT ck_msgp_noself  CHECK (reply_to_message_id IS NULL OR reply_to_message_id <> message_id),
    CONSTRAINT ck_msgp_deleted CHECK (NOT is_deleted OR body IS NULL)
) PARTITION BY RANGE (sent_at);

-- ---------------------------------------------------------------------
-- 2. Monthly partitions, Jan 2025 .. Dec 2026, plus a DEFAULT partition
--    (the seed data runs from 1 Jan 2025 to 30 Jun 2026 IST)
-- ---------------------------------------------------------------------
DO $$
DECLARE
    m date := DATE '2025-01-01';
BEGIN
    WHILE m < DATE '2027-01-01' LOOP
        EXECUTE format(
            'CREATE TABLE %I PARTITION OF messages_partitioned
                 FOR VALUES FROM (%L) TO (%L)',
            'messages_p' || to_char(m, 'YYYY_MM'),
            to_char(m, 'YYYY-MM-DD') || ' 00:00:00+05:30',
            to_char(m + INTERVAL '1 month', 'YYYY-MM-DD') || ' 00:00:00+05:30');
        m := (m + INTERVAL '1 month')::date;
    END LOOP;
END $$;

CREATE TABLE messages_p_default PARTITION OF messages_partitioned DEFAULT;

-- ---------------------------------------------------------------------
-- 3. Indexes: same set as sql/05_indexes.sql. Created on the parent, PostgreSQL
--    builds a matching (smaller) index on every partition, including future ones.
--    The primary key (message_id, sent_at) already serves lookups by message_id.
-- ---------------------------------------------------------------------
CREATE INDEX idx_msgp_chat_sent  ON messages_partitioned (chat_id, sent_at DESC);
CREATE INDEX idx_msgp_sent_at    ON messages_partitioned (sent_at) INCLUDE (chat_id, sender_id, message_type);
CREATE INDEX idx_msgp_forwarded  ON messages_partitioned (sender_id, sent_at) WHERE is_forwarded;
CREATE INDEX idx_msgp_reply_to   ON messages_partitioned (reply_to_message_id) WHERE reply_to_message_id IS NOT NULL;

-- ---------------------------------------------------------------------
-- 4. Copy the data and refresh statistics
-- ---------------------------------------------------------------------
INSERT INTO messages_partitioned
SELECT message_id, chat_id, sender_id, sent_at, message_type, body, media_id,
       reply_to_message_id, is_forwarded, is_deleted, edited_at
FROM messages;

-- keep the identity sequence ahead of the copied ids
SELECT setval(pg_get_serial_sequence('messages_partitioned', 'message_id'),
              (SELECT max(message_id) FROM messages_partitioned));

VACUUM (ANALYZE) messages_partitioned;

-- ---------------------------------------------------------------------
-- 5. Checks
-- ---------------------------------------------------------------------

-- 5a. Same number of rows as the original table (both numbers must match)
SELECT (SELECT count(*) FROM messages)             AS rows_messages,
       (SELECT count(*) FROM messages_partitioned) AS rows_partitioned;

-- 5b. Rows per partition. rows in messages_p_default must be 0; if not, create
--     the missing month partitions (see the maintenance snippet below).
SELECT tableoid::regclass AS partition, count(*) AS rows,
       min(sent_at) AS first_msg, max(sent_at) AS last_msg
FROM messages_partitioned
GROUP BY tableoid
ORDER BY 1;

-- ---------------------------------------------------------------------
-- 6. Partition pruning demos (plain EXPLAIN: look at WHICH partitions appear)
-- ---------------------------------------------------------------------

-- 6a. R10 / R14 / R17 shape: one month. Expect ONE partition (messages_p2026_06)
--     in the plan and every other month absent.
EXPLAIN (COSTS OFF)
SELECT sent_at::date AS day, count(DISTINCT sender_id) AS active_senders, count(*) AS messages
FROM messages_partitioned
WHERE sent_at >= '2026-06-01 00:00:00+05:30' AND sent_at < '2026-07-01 00:00:00+05:30'
GROUP BY 1 ORDER BY 1;

-- 6b. R08 shape: everything before a date. Only the months up to that date appear.
EXPLAIN (COSTS OFF)
SELECT message_id, chat_id FROM messages_partitioned
WHERE sent_at < '2025-03-01 00:00:00+05:30'
ORDER BY sent_at LIMIT 500;

-- 6c. R02 shape: filter on chat_id only. There is NO pruning (chat_id is not the
--     partition key); the planner merges the per-partition (chat_id, sent_at DESC)
--     indexes. This is the cost of choosing time as the partition key.
EXPLAIN (COSTS OFF)
SELECT message_id, sender_id, sent_at, message_type, body, reply_to_message_id
FROM messages_partitioned
WHERE chat_id = 22556
ORDER BY sent_at DESC
LIMIT 50;

-- 6d. R16 / W03 shape: lookup by message_id only. No pruning either; every
--     partition's primary-key index is probed once.
EXPLAIN (COSTS OFF)
SELECT * FROM messages_partitioned WHERE message_id = 119989;

-- 6e. Same lookup when the caller also knows the message time: pruned to one partition.
--     (This is why an app that carries sent_at next to message_id gets the best plans.)
EXPLAIN (COSTS OFF)
SELECT * FROM messages_partitioned
WHERE message_id = 119989
  AND sent_at >= '2026-06-01 00:00:00+05:30' AND sent_at < '2026-07-01 00:00:00+05:30';

-- ---------------------------------------------------------------------
-- 7. Timed comparison, same queries on both tables (EXPLAIN ANALYZE).
--    Read the "Execution Time" line. Run each one 3 times and average, as for
--    every other benchmark in this project.
-- ---------------------------------------------------------------------

-- 7a. R10 shape, original table
EXPLAIN (ANALYZE, BUFFERS)
SELECT sent_at::date AS day, count(DISTINCT sender_id) AS active_senders, count(*) AS messages
FROM messages
WHERE sent_at >= '2026-06-01 00:00:00+05:30' AND sent_at < '2026-07-01 00:00:00+05:30'
GROUP BY 1 ORDER BY 1;

-- 7b. R10 shape, partitioned table
EXPLAIN (ANALYZE, BUFFERS)
SELECT sent_at::date AS day, count(DISTINCT sender_id) AS active_senders, count(*) AS messages
FROM messages_partitioned
WHERE sent_at >= '2026-06-01 00:00:00+05:30' AND sent_at < '2026-07-01 00:00:00+05:30'
GROUP BY 1 ORDER BY 1;

-- 7c. R02 shape, original table
EXPLAIN (ANALYZE, BUFFERS)
SELECT message_id, sender_id, sent_at, message_type, body, reply_to_message_id
FROM messages WHERE chat_id = 22556 ORDER BY sent_at DESC LIMIT 50;

-- 7d. R02 shape, partitioned table
EXPLAIN (ANALYZE, BUFFERS)
SELECT message_id, sender_id, sent_at, message_type, body, reply_to_message_id
FROM messages_partitioned WHERE chat_id = 22556 ORDER BY sent_at DESC LIMIT 50;

-- 7e. R20 shape (whole-table aggregate), original and partitioned
EXPLAIN (ANALYZE, BUFFERS)
SELECT EXTRACT(HOUR FROM sent_at) AS hour, message_type, count(*) AS messages
FROM messages GROUP BY 1, 2 ORDER BY 1, 2;

EXPLAIN (ANALYZE, BUFFERS)
SELECT EXTRACT(HOUR FROM sent_at) AS hour, message_type, count(*) AS messages
FROM messages_partitioned GROUP BY 1, 2 ORDER BY 1, 2;

